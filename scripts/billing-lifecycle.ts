// Opt-in Stripe TEST-mode integration. Creates and cleans up a test-clock customer.
import Stripe from 'stripe';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync, spawn } from 'node:child_process';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
import { fixture } from '../tests/helpers/billing-fixture';
import { stripeWebhook, reconcileBilling, billingRoute } from '../src/server/billing';
import { organizationPlan } from '../src/server/plans';
const vars=Object.fromEntries(readFileSync('.dev.vars.stripe','utf8').trim().split('\n').map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1)]}));
assert.ok(vars.STRIPE_SECRET_KEY?.startsWith('sk_test_') || vars.STRIPE_SECRET_KEY?.startsWith('rk_test_'),'TEST key required');
const stripe=new Stripe(vars.STRIPE_SECRET_KEY);
const {price_id:priceId}=JSON.parse(readFileSync('docs/stripe-sandbox.json','utf8'));
const {env,sql}=fixture();
Object.assign(env,vars,{BASE_URL:'http://localhost:3000'});
const childEnv={...process.env,STRIPE_API_KEY:vars.STRIPE_SECRET_KEY};
const secret=execFileSync('stripe',['listen','--print-secret'],{env:childEnv,encoding:'utf8',timeout:30000}).trim();
assert.ok(secret.startsWith('whsec_'));
env.STRIPE_WEBHOOK_SECRET=secret;
const deliveries:{type:string,status:number}[]=[];
const server=createServer(async(req,res)=>{
 try {
 const chunks:Buffer[]=[];for await(const chunk of req)chunks.push(Buffer.from(chunk));
 const body=Buffer.concat(chunks).toString();
 const response=await stripeWebhook(new Request('http://localhost/api/billing/webhook',{method:'POST',body,headers:{'stripe-signature':String(req.headers['stripe-signature']||'')}}),env);
 deliveries.push({type:JSON.parse(body).type,status:response.status});
 res.writeHead(response.status);res.end(await response.text());
 }catch(e:any){res.writeHead(e.status||500);res.end('retry');}
});
await new Promise<void>(r=>server.listen(0,'127.0.0.1',r));
const port=(server.address() as any).port;
const listener=spawn('stripe',['listen','--latest','--events','customer.subscription.created,customer.subscription.updated,customer.subscription.deleted,invoice.paid,invoice.payment_failed,charge.refunded','--forward-to',`http://127.0.0.1:${port}`],{env:childEnv,detached:true,stdio:['ignore','pipe','pipe']});
let ready=false;let diagnostic='';
const parse=(b:Buffer)=>{const t=b.toString();if(t.includes('Ready!'))ready=true;diagnostic+=(t.replace(/whsec_\w+/g,'[redacted]'));};
listener.stdout.on('data',parse);listener.stderr.on('data',parse);
const delay=(ms:number)=>new Promise(r=>setTimeout(r,ms));
async function until(check:()=>Promise<boolean>|boolean,label:string,timeout=45000){const start=Date.now();while(Date.now()-start<timeout){if(await check())return;await delay(500);}throw Error('Timed out: '+label);}
const report:{checks:string[],deliveries:typeof deliveries,clock_id?:string,subscription_id?:string}={checks:[],deliveries};
let clock:Stripe.TestHelpers.TestClock|undefined;
let subscription:Stripe.Subscription|undefined;
try {
 await until(()=>ready,'Stripe CLI listener readiness',30000);
 clock=await stripe.testHelpers.testClocks.create({frozen_time:Math.floor(Date.now()/1000),name:'TrackRank billing acceptance'});
 const customer=await stripe.customers.create({test_clock:clock.id,name:'TrackRank automated test — no email'});
 const pm=await stripe.paymentMethods.attach('pm_card_visa',{customer:customer.id});
 await stripe.customers.update(customer.id,{invoice_settings:{default_payment_method:pm.id}});
 sql.exec('DELETE FROM billing_customers;');
 sql.prepare("INSERT INTO billing_customers(org_id,customer_id,updated_at) VALUES('org',?,?)").run(customer.id,Date.now());
 sql.prepare("INSERT INTO billing_prices VALUES(?,'starter-v1',0)").run(priceId);
 subscription=await stripe.subscriptions.create({customer:customer.id,items:[{price:priceId}],payment_behavior:'error_if_incomplete'});
 assert.equal(subscription.status,'active');
 await until(()=>sql.prepare("SELECT status FROM billing_customers WHERE org_id='org'").get()?.status==='active','signed initial webhook');
 assert.equal((await organizationPlan(env,'org')).version,'starter-v1');
 report.checks.push('Initial real Stripe test-card invoice paid; CLI-signed webhook grants exact Starter revision');console.log('PASS:',report.checks.at(-1));
 const failed=await stripe.paymentMethods.attach('pm_card_chargeCustomerFail',{customer:customer.id});
 await stripe.customers.update(customer.id,{invoice_settings:{default_payment_method:failed.id}});
 await stripe.subscriptions.update(subscription.id,{default_payment_method:failed.id});
 const renewal=subscription.items.data[0].current_period_end+3600;
 await stripe.testHelpers.testClocks.advance(clock.id,{frozen_time:renewal});
 await until(async()=>(await stripe.testHelpers.testClocks.retrieve(clock!.id)).status==='ready','renewal clock ready',60000);
 await until(async()=>(await stripe.subscriptions.retrieve(subscription!.id)).status==='past_due','failed renewal status',60000);
 await until(()=>sql.prepare("SELECT status FROM billing_customers WHERE org_id='org'").get()?.status==='past_due','signed failed-renewal webhook',60000);
 await assert.rejects(organizationPlan(env,'org'),/Subscription payment required/);
 report.checks.push('Clock-advanced renewal declines; signed webhook removes paid access');console.log('PASS:',report.checks.at(-1));
 const recovery=await stripe.paymentMethods.attach('pm_card_visa',{customer:customer.id});
 await stripe.customers.update(customer.id,{invoice_settings:{default_payment_method:recovery.id}});
 await stripe.subscriptions.update(subscription.id,{default_payment_method:recovery.id});
 const current=await stripe.subscriptions.retrieve(subscription.id);
 const invoiceId=typeof current.latest_invoice==='string'?current.latest_invoice:current.latest_invoice!.id;
 await stripe.invoices.pay(invoiceId,{payment_method:recovery.id});
 await until(()=>sql.prepare("SELECT status FROM billing_customers WHERE org_id='org'").get()?.status==='active','signed recovery webhook');
 assert.equal((await organizationPlan(env,'org')).version,'starter-v1');
 report.checks.push('Failed invoice paid after payment-method update; signed webhook restores access');console.log('PASS:',report.checks.at(-1));
 const invoicePayments=await stripe.invoicePayments.list({invoice:invoiceId,limit:10});
 const payment=invoicePayments.data.find(p=>p.payment.type==='payment_intent');
 assert.ok(payment?.payment.payment_intent);
 const paymentIntent=typeof payment!.payment.payment_intent==='string'?payment!.payment.payment_intent:payment!.payment.payment_intent!.id;
 await stripe.refunds.create({payment_intent:paymentIntent});
 await until(()=>Boolean(sql.prepare("SELECT id FROM billing_alerts WHERE kind='charge.refunded'").get()),'signed refund webhook resolves subscription');
 assert.equal((await organizationPlan(env,'org')).version,'starter-v1');
 report.checks.push('Real test refund traverses invoice-payment graph and records operator review without silently canceling subscription');console.log('PASS:',report.checks.at(-1));
 const canceled=await stripe.subscriptions.update(subscription.id,{cancel_at_period_end:true});
 await until(()=>sql.prepare("SELECT cancel_at_period_end FROM billing_customers WHERE org_id='org'").get()?.cancel_at_period_end===1,'period-end cancellation webhook');
 assert.equal((await organizationPlan(env,'org')).version,'starter-v1');
 await stripe.testHelpers.testClocks.advance(clock.id,{frozen_time:canceled.items.data[0].current_period_end+3600});
 await until(async()=>(await stripe.testHelpers.testClocks.retrieve(clock!.id)).status==='ready','cancellation clock ready',60000);
 await until(()=>sql.prepare("SELECT status FROM billing_customers WHERE org_id='org'").get()?.status==='canceled','period-end cancellation webhook',60000);
 await assert.rejects(organizationPlan(env,'org'),/Subscription payment required/);
 report.checks.push('Period-end cancellation retains access until expiry, then signed webhook blocks access');console.log('PASS:',report.checks.at(-1));
 const portal=await billingRoute(new Request('http://localhost',{method:'POST'}),env,{userId:'alice',orgId:'org',role:'owner'},'/billing/portal');
 assert.equal(portal.status,200);
 report.checks.push('Billing portal remains available after cancellation');
 sql.exec("UPDATE billing_customers SET status='active',updated_at=0 WHERE org_id='org'");
 await reconcileBilling(env);
 assert.equal(sql.prepare("SELECT status FROM billing_customers WHERE org_id='org'").get()?.status,'canceled');
 report.checks.push('Scheduled reconciliation repairs deliberately corrupted local subscription state');
 report.clock_id=clock.id;report.subscription_id=subscription.id;
 mkdirSync('reports/billing-acceptance',{recursive:true});
 writeFileSync('reports/billing-acceptance/lifecycle.json',JSON.stringify({tested_at:new Date().toISOString(),...report},null,2)+'\n');
 console.log('PASS: acceptance evidence saved; no real funds or email used');
} finally {
 try { process.kill(-listener.pid!, 'SIGTERM'); } catch {}
 listener.stdout.destroy();listener.stderr.destroy();
 server.close();server.closeAllConnections();
 if(clock)await stripe.testHelpers.testClocks.del(clock.id);
}
